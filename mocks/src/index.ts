/**
 * Simula AI Layer (4001), DB Layer (4002) e Data Layer (4003) com respostas fixas,
 * nos contratos descritos no documento da Fase 6.
 * FAIL=ai|db|data faz o layer escolhido responder HTTP 500.
 * VALIDATION_FAIL=true faz o DB Layer reprovar o plano no sandbox.
 */
import express, { Request, RequestHandler } from 'express';

const DELAY_MS = Number(process.env.MOCK_DELAY_MS ?? 500);
const FAIL = process.env.FAIL ?? '';

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

type Routes = Record<string, (req: Request) => unknown>;

function layer(name: 'ai' | 'db' | 'data', port: number, routes: Routes) {
  const app = express();
  app.use(express.json());

  for (const [route, respond] of Object.entries(routes)) {
    const [method, path] = route.split(' ');
    const handler: RequestHandler = async (req, res) => {
      await sleep(DELAY_MS);
      if (FAIL === name) {
        console.log(`[${name}-layer] ${route} -> 500 (FAIL=${FAIL})`);
        res.status(500).json({ error: 'falha simulada' });
        return;
      }
      console.log(`[${name}-layer] ${route} -> 200`);
      res.json(respond(req));
    };
    if (method === 'GET') app.get(path, handler);
    else app.post(path, handler);
  }

  app.listen(port, () => console.log(`${name}-layer mock on :${port}`));
}

